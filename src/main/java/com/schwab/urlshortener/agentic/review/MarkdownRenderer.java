package com.schwab.urlshortener.agentic.review;

import com.schwab.urlshortener.agentic.model.ArtifactSource;
import com.schwab.urlshortener.agentic.model.ExecutionMode;
import com.schwab.urlshortener.agentic.model.ImpactAnalysis;
import com.schwab.urlshortener.agentic.model.ImplementationPlan;
import com.schwab.urlshortener.agentic.model.QualityGateReport;
import com.schwab.urlshortener.agentic.model.RequirementSpec;
import com.schwab.urlshortener.agentic.model.RiskAssessment;
import com.schwab.urlshortener.agentic.model.TestPlan;
import org.springframework.stereotype.Component;

import java.util.List;

/**
 * Renders artifacts as human-reviewable Markdown. Every rendered artifact
 * starts with a provenance line, and every combined report starts with an
 * execution-mode banner, so a document copied out of this system (into a
 * ticket, a PR description, an email) still says what produced it.
 */
@Component
public class MarkdownRenderer {

    public static final String DEMO_BANNER = """
            > **Execution mode: DETERMINISTIC_DEMO. No language model was called.**
            > Stages 1-5 were produced by rule-based templates: keyword classification, a vague-term lexicon, \
            and keyword matching against a curated catalog of this codebase's components. Treat this as a \
            demonstration of the orchestration pipeline and its guardrails, not as AI analysis of the requirement.
            """;

    public static String llmBanner(String model) {
        return """
                > **Execution mode: LLM (`%s`).**
                > Stages 1-5 were generated by a Claude model through the Anthropic API, constrained to each \
                artifact's JSON schema. Stage 6 (quality gate) is deterministic code. Model output can be wrong \
                or incomplete: review before acting on it.
                """.formatted(model);
    }

    public String banner(ExecutionMode mode, String model) {
        return mode == ExecutionMode.LLM ? llmBanner(model) : DEMO_BANNER;
    }

    public String provenance(ArtifactSource source, String model) {
        return switch (source) {
            case LLM -> "_Source: generated by `" + model + "` (LLM)._\n\n";
            case DETERMINISTIC_DEMO -> "_Source: deterministic rule-based demo logic. No model was called._\n\n";
            case DETERMINISTIC_GUARDRAIL -> "_Source: deterministic quality gate (never model-generated)._\n\n";
        };
    }

    public String render(Object artifact) {
        if (artifact instanceof RequirementSpec spec) {
            return requirements(spec);
        } else if (artifact instanceof ImpactAnalysis impact) {
            return impact(impact);
        } else if (artifact instanceof ImplementationPlan plan) {
            return plan(plan);
        } else if (artifact instanceof TestPlan tests) {
            return tests(tests);
        } else if (artifact instanceof RiskAssessment risks) {
            return risks(risks);
        } else if (artifact instanceof QualityGateReport gate) {
            return gate(gate);
        }
        throw new IllegalArgumentException("No renderer for " + artifact.getClass().getName());
    }

    String requirements(RequirementSpec spec) {
        StringBuilder sb = new StringBuilder("## 1. Requirements\n\n");
        sb.append("**").append(cell(spec.title())).append("**: ").append(cell(spec.summary())).append("\n\n");
        sb.append("### Functional\n\n");
        list(sb, spec.functionalRequirements(), s -> "**" + s.id() + "**: " + cell(s.text()));
        sb.append("### Non-functional\n\n");
        list(sb, spec.nonFunctionalRequirements(), s -> "**" + s.id() + "**: " + cell(s.text()));
        sb.append("### Acceptance criteria\n\n| ID | Verifies | Given | When | Then |\n|---|---|---|---|---|\n");
        for (RequirementSpec.AcceptanceCriterion ac : safe(spec.acceptanceCriteria())) {
            sb.append("| ").append(ac.id()).append(" | ").append(cell(ac.sourceRequirementId())).append(" | ")
                    .append(cell(ac.given())).append(" | ").append(cell(ac.when())).append(" | ")
                    .append(cell(ac.then())).append(" |\n");
        }
        sb.append("\n### Ambiguities and assumptions\n\n");
        if (safe(spec.ambiguities()).isEmpty()) {
            sb.append("_None identified._\n\n");
        } else {
            sb.append("| ID | Ambiguity | Question for the requirement owner | Assumption taken |\n|---|---|---|---|\n");
            for (RequirementSpec.Ambiguity a : spec.ambiguities()) {
                sb.append("| ").append(a.id()).append(" | ").append(cell(a.statement())).append(" | ")
                        .append(cell(a.question())).append(" | ").append(cell(a.assumption())).append(" |\n");
            }
            sb.append('\n');
        }
        sb.append("### Out of scope\n\n");
        list(sb, spec.outOfScope(), this::cell);
        return sb.toString();
    }

    String impact(ImpactAnalysis impact) {
        StringBuilder sb = new StringBuilder("## 2. Impact analysis\n\n");
        if (safe(impact.impactedComponents()).isEmpty()) {
            sb.append("_No existing component matched._\n\n");
        } else {
            sb.append("| Component | Change | Related criteria | Reason |\n|---|---|---|---|\n");
            for (ImpactAnalysis.ImpactedComponent ic : impact.impactedComponents()) {
                sb.append("| `").append(cell(ic.component())).append("` | ").append(ic.changeType()).append(" | ")
                        .append(String.join(", ", safe(ic.relatedCriteria()))).append(" | ")
                        .append(cell(ic.reason())).append(" |\n");
            }
            sb.append('\n');
        }
        if (!safe(impact.newComponents()).isEmpty()) {
            sb.append("### Proposed new components\n\n");
            list(sb, impact.newComponents(), p -> "`" + cell(p.name()) + "` in `" + cell(p.packageName()) + "`: " + cell(p.responsibility()));
        }
        if (!safe(impact.dataFlows()).isEmpty()) {
            sb.append("### Data flows\n\n");
            list(sb, impact.dataFlows(), f -> "**" + cell(f.name()) + "**: "
                    + safe(f.steps()).stream().map(s -> "`" + cell(s) + "`").collect(java.util.stream.Collectors.joining(" → "))
                    + (f.description() == null ? "" : ". " + cell(f.description())));
        }
        sb.append("### Unaffected areas\n\n");
        list(sb, impact.unaffectedAreas(), this::cell);
        return sb.toString();
    }

    String plan(ImplementationPlan plan) {
        StringBuilder sb = new StringBuilder("## 3. Implementation plan\n\n| ID | Task | Depends on | Components | Criteria |\n|---|---|---|---|---|\n");
        for (ImplementationPlan.PlanTask t : safe(plan.tasks())) {
            sb.append("| ").append(t.id()).append(" | **").append(cell(t.title())).append("**<br>").append(cell(t.description()))
                    .append(" | ").append(joinOrDash(t.dependsOn())).append(" | ").append(joinOrDash(t.components()))
                    .append(" | ").append(joinOrDash(t.acceptanceCriteria())).append(" |\n");
        }
        return sb.append('\n').toString();
    }

    String tests(TestPlan tests) {
        StringBuilder sb = new StringBuilder("## 4. Test plan\n\n| ID | Level | Target | Scenario | Criteria |\n|---|---|---|---|---|\n");
        for (TestPlan.TestCase tc : safe(tests.testCases())) {
            sb.append("| ").append(tc.id()).append(" | ").append(tc.level()).append(" | `").append(cell(tc.targetTestClass()))
                    .append("` | **").append(cell(tc.title())).append("**<br>").append(cell(tc.scenario()))
                    .append(" | ").append(joinOrDash(tc.acceptanceCriteria())).append(" |\n");
        }
        return sb.append('\n').toString();
    }

    String risks(RiskAssessment risks) {
        StringBuilder sb = new StringBuilder("## 5. Risk assessment\n\n| ID | Severity | Risk | Mitigation | Components |\n|---|---|---|---|---|\n");
        for (RiskAssessment.Risk r : safe(risks.risks())) {
            sb.append("| ").append(r.id()).append(" | ").append(r.severity()).append(" | ").append(cell(r.description()))
                    .append(" | ").append(cell(r.mitigation())).append(" | ").append(joinOrDash(r.components())).append(" |\n");
        }
        return sb.append('\n').toString();
    }

    String gate(QualityGateReport gate) {
        StringBuilder sb = new StringBuilder("## 6. Quality gate\n\n");
        sb.append(gate.passed() ? "**PASSED**" : "**FAILED**").append(": ").append(gate.blockerCount()).append(" blocker(s), ")
                .append(gate.warningCount()).append(" warning(s).");
        if (!gate.passed()) {
            sb.append(" Approval is blocked until every blocker is resolved.");
        }
        QualityGateReport.Metrics m = gate.metrics();
        sb.append("\n\n| Metric | Value |\n|---|---|\n")
                .append("| Acceptance criteria | ").append(m.acceptanceCriteria()).append(" |\n")
                .append("| Criteria covered by a task | ").append(m.criteriaCoveredByTasks()).append(" |\n")
                .append("| Criteria covered by a test | ").append(m.criteriaCoveredByTests()).append(" |\n")
                .append("| Impacted components | ").append(m.impactedComponents()).append(" |\n")
                .append("| Tasks | ").append(m.tasks()).append(" |\n")
                .append("| Test cases | ").append(m.testCases()).append(" |\n")
                .append("| Risks | ").append(m.risks()).append(" |\n")
                .append("| Open ambiguities | ").append(m.openAmbiguities()).append(" |\n\n")
                .append("| Severity | Rule | Finding |\n|---|---|---|\n");
        for (QualityGateReport.Finding f : gate.findings()) {
            sb.append("| ").append(f.severity()).append(" | `").append(f.rule()).append("` | ").append(cell(f.message())).append(" |\n");
        }
        return sb.append('\n').toString();
    }

    private <T> void list(StringBuilder sb, List<T> items, java.util.function.Function<T, String> line) {
        if (safe(items).isEmpty()) {
            sb.append("_None._\n\n");
            return;
        }
        for (T item : items) {
            sb.append("- ").append(line.apply(item)).append('\n');
        }
        sb.append('\n');
    }

    private String joinOrDash(List<String> values) {
        return safe(values).isEmpty() ? "-" : cell(String.join(", ", values));
    }

    /** Escapes characters that would break a Markdown table cell, and flattens newlines. */
    public String cell(String value) {
        if (value == null) {
            return "";
        }
        return value.replace("|", "\\|").replaceAll("\\R", " ");
    }

    private static <T> List<T> safe(List<T> list) {
        return list == null ? List.of() : list;
    }
}
