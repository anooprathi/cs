package com.schwab.urlshortener.agentic.api;

import com.schwab.urlshortener.agentic.SdlcArtifact;
import com.schwab.urlshortener.agentic.SdlcRun;
import com.schwab.urlshortener.agentic.model.ArtifactSource;
import com.schwab.urlshortener.agentic.model.ExecutionMode;
import com.schwab.urlshortener.agentic.model.SdlcStage;

import java.time.Instant;
import java.util.List;

/**
 * A run with a summary of every stage. {@code executionNotice} repeats, in
 * plain words, what produced the artifacts. A client that only shows
 * this response still tells its reader whether a model was involved.
 */
public record SdlcRunResponse(
        Long id,
        String title,
        ExecutionMode executionMode,
        String model,
        String executionNotice,
        SdlcRun.Status status,
        Boolean qualityGatePassed,
        Integer blockerCount,
        Integer warningCount,
        String failureReason,
        Review review,
        Instant createdAt,
        Instant completedAt,
        List<StageSummary> stages
) {

    public static final String DEMO_NOTICE = "DETERMINISTIC_DEMO: no language model was called. Stages 1-5 are "
            + "rule-based template output. Stage 6 is the deterministic quality gate.";
    public static final String LLM_NOTICE = "LLM: stages 1-5 were generated by the model named in 'model' via the "
            + "Anthropic API. Stage 6 is the deterministic quality gate. Model output requires human review.";

    public record Review(String reviewer, String comment, Instant reviewedAt) {
    }

    public record StageSummary(
            SdlcStage stage,
            ArtifactSource source,
            SdlcArtifact.Status status,
            String model,
            Long durationMs,
            Long inputTokens,
            Long outputTokens,
            String errorMessage
    ) {
        static StageSummary from(SdlcArtifact a) {
            return new StageSummary(a.getStage(), a.getSource(), a.getStatus(), a.getModel(), a.getDurationMs(),
                    a.getInputTokens(), a.getOutputTokens(), a.getErrorMessage());
        }
    }

    public static SdlcRunResponse from(SdlcRun run, List<SdlcArtifact> artifacts) {
        Review review = run.getReviewedAt() == null ? null
                : new Review(run.getReviewer(), run.getReviewComment(), run.getReviewedAt());
        return new SdlcRunResponse(run.getId(), run.getTitle(), run.getExecutionMode(), run.getModel(),
                run.getExecutionMode() == ExecutionMode.LLM ? LLM_NOTICE : DEMO_NOTICE,
                run.getStatus(), run.getQualityGatePassed(), run.getBlockerCount(), run.getWarningCount(),
                run.getFailureReason(), review, run.getCreatedAt(), run.getCompletedAt(),
                artifacts.stream().map(StageSummary::from).toList());
    }
}
