package com.schwab.urlshortener.workflow.engine;

import com.schwab.urlshortener.agentic.review.MarkdownRenderer;
import com.schwab.urlshortener.workflow.artifact.DocumentationBundle;
import com.schwab.urlshortener.workflow.artifact.PolicyReport;
import com.schwab.urlshortener.workflow.artifact.ReadinessReport;
import com.schwab.urlshortener.workflow.artifact.TestReport;
import com.schwab.urlshortener.workflow.artifact.InterfaceContract;
import com.schwab.urlshortener.workflow.workspace.ChangePatch;
import org.springframework.stereotype.Component;

import java.util.List;

/**
 * Markdown for every workflow artifact, each starting with an origin line so a
 * copied artifact still says what produced it. Agent artifact types reuse the
 * agentic layer's MarkdownRenderer. Workflow-specific types are rendered here.
 */
@Component
public class WorkflowArtifactRenderer {

    private static final String NL = "\n";

    private final MarkdownRenderer agentRenderer;
    private final com.fasterxml.jackson.databind.ObjectMapper json;

    public WorkflowArtifactRenderer(MarkdownRenderer agentRenderer, com.fasterxml.jackson.databind.ObjectMapper json) {
        this.agentRenderer = agentRenderer;
        this.json = json;
    }

    public String render(String name, Object content, ArtifactOrigin origin, String model) {
        return "### `" + name + "`" + NL + NL + originLine(origin, model) + body(content);
    }

    public static String originLine(ArtifactOrigin origin, String model) {
        String text = switch (origin) {
            case LLM -> "_Origin: generated by `" + model + "` (LLM)._";
            case DETERMINISTIC_DEMO -> "_Origin: rule-based demo logic (DETERMINISTIC_DEMO). No model was called._";
            case DETERMINISTIC -> "_Origin: deterministic code (identical in every mode)._";
            case EXTERNAL_COMMAND -> "_Origin: result of running an external command._";
        };
        return text + NL + NL;
    }

    private String body(Object content) {
        if (content instanceof TestReport r) {
            return testReport(r);
        } else if (content instanceof PolicyReport r) {
            return policyReport(r);
        } else if (content instanceof DocumentationBundle d) {
            return documentation(d);
        } else if (content instanceof ReadinessReport r) {
            return readiness(r);
        } else if (content instanceof ChangePatch p) {
            return patch(p);
        } else if (content instanceof InterfaceContract c) {
            return contract(c);
        }
        try {
            // agentic artifact types render with their own section headings; demote them one level
            return agentRenderer.render(content).replaceFirst("^## ", "#### ");
        } catch (IllegalArgumentException unknownType) {
            // A type with no dedicated renderer must never fail the task that produced it: fall back to its JSON.
            try {
                return "```json" + NL + json.writerWithDefaultPrettyPrinter().writeValueAsString(content) + NL + "```" + NL + NL;
            } catch (com.fasterxml.jackson.core.JsonProcessingException e) {
                return "_" + content.getClass().getSimpleName() + " (not renderable)_" + NL + NL;
            }
        }
    }

    private String patch(ChangePatch p) {
        StringBuilder sb = new StringBuilder(cell(p.summary())).append(NL).append(NL);
        if (p.notice() != null) {
            sb.append("> ").append(cell(p.notice())).append(NL).append(NL);
        }
        sb.append("Kind **").append(p.kind()).append("**, author `").append(p.author()).append("`. Base commit `")
                .append(p.baseCommit() == null ? "-" : p.baseCommit()).append("`, applied in isolated workspace: **")
                .append(p.applied() ? "yes" : "no").append("**.").append(NL).append(NL);
        if (!p.testFiles().isEmpty()) {
            sb.append("Test sources in this patch: ").append(String.join(", ", p.testFiles().stream().map(f -> "`" + f + "`").toList()))
                    .append(NL).append(NL);
        }
        if (!p.policyViolations().isEmpty()) {
            sb.append("**Change-control violations (nothing was written):**").append(NL).append(NL);
            p.policyViolations().forEach(v -> sb.append("- ").append(cell(v)).append(NL));
            sb.append(NL);
        }
        if (!p.protectedPathsTouched().isEmpty()) {
            sb.append("Protected paths touched (human approval required): ").append(String.join(", ", p.protectedPathsTouched()))
                    .append(NL).append(NL);
        }
        if (!p.files().isEmpty()) {
            sb.append("| File | Action | Bytes | Rationale |").append(NL).append("|---|---|---:|---|").append(NL);
            p.files().forEach(f -> sb.append("| `").append(cell(f.path())).append("` | ").append(f.action()).append(" | ").append(f.bytes())
                    .append(" | ").append(cell(f.rationale())).append(" |").append(NL));
            sb.append(NL);
        }
        if (!p.validation().isEmpty()) {
            sb.append("| Validation command | argv | Exit | Result |").append(NL).append("|---|---|---:|---|").append(NL);
            p.validation().forEach(v -> sb.append("| ").append(v.name()).append(" | `").append(cell(String.join(" ", v.argv()))).append("` | ")
                    .append(v.exitCode()).append(" | ").append(v.passed() ? "pass" : "FAIL").append(" |").append(NL));
            sb.append(NL);
        }
        if (p.unifiedDiff() != null && !p.unifiedDiff().isBlank()) {
            String diff = p.unifiedDiff().length() > 6000
                    ? p.unifiedDiff().substring(0, 6000) + NL + "... (truncated; the full diff is in the artifact JSON)"
                    : p.unifiedDiff();
            sb.append("```diff").append(NL).append(diff.replace("```", "'''")).append(NL).append("```").append(NL).append(NL);
        }
        return sb.toString();
    }

    private String contract(InterfaceContract c) {
        StringBuilder sb = new StringBuilder("Source **").append(c.source()).append("**: ").append(cell(c.summary())).append(NL).append(NL);
        if (c.source() == InterfaceContract.Source.DERIVED_PROPOSAL) {
            sb.append("> No code was generated, so this is a proposal derived from the design, not an exact contract.").append(NL).append(NL);
        }
        if (c.apiChanges().isEmpty()) {
            sb.append("API changes: _none_.").append(NL).append(NL);
        } else {
            sb.append("| Method | Path | Change | Detail |").append(NL).append("|---|---|---|---|").append(NL);
            c.apiChanges().forEach(a -> sb.append("| ").append(a.method() == null ? "-" : a.method()).append(" | `").append(cell(a.path()))
                    .append("` | ").append(cell(a.change())).append(" | ").append(cell(a.detail())).append(" |").append(NL));
            sb.append(NL);
        }
        if (c.schemaChanges().isEmpty()) {
            sb.append("Schema changes: _none_.").append(NL).append(NL);
        } else {
            sb.append("| Table | Column | Change | Migration DDL |").append(NL).append("|---|---|---|---|").append(NL);
            c.schemaChanges().forEach(s -> sb.append("| ").append(cell(s.table())).append(" | ").append(s.column() == null ? "-" : cell(s.column()))
                    .append(" | ").append(cell(s.change())).append(" | ").append(s.ddl() == null ? "_not derived_" : "`" + cell(s.ddl()) + "`")
                    .append(" |").append(NL));
            sb.append(NL);
        }
        return sb.toString();
    }

    private String testReport(TestReport r) {
        StringBuilder sb = new StringBuilder();
        sb.append("Runner `").append(r.runner()).append("`. Product tests executed: **")
                .append(r.productTestsExecuted() ? "yes" : "no").append("**. ")
                .append(r.executed()).append(" executed, ").append(r.passed()).append(" passed, ")
                .append(r.failed()).append(" failed, ").append(r.notExecuted()).append(" not executed.").append(NL).append(NL);
        if (r.notice() != null) {
            sb.append("> ").append(cell(r.notice())).append(NL).append(NL);
        }
        if (r.command() != null) {
            sb.append("Command: `").append(cell(r.command())).append("`, exit code ").append(r.exitCode()).append(".").append(NL).append(NL);
        }
        sb.append("| Test case | Target | Status | Detail |").append(NL).append("|---|---|---|---|").append(NL);
        for (TestReport.Result res : r.results()) {
            sb.append("| ").append(res.testCaseId()).append(" | `").append(cell(res.target())).append("` | ")
                    .append(res.status()).append(" | ").append(cell(res.detail())).append(" |").append(NL);
        }
        return sb.append(NL).toString();
    }

    private String policyReport(PolicyReport r) {
        StringBuilder sb = new StringBuilder(r.passed() ? "**PASSED**" : "**FAILED**")
                .append(": ").append(r.blockers()).append(" blocker(s), ").append(r.warnings()).append(" warning(s). Rules evaluated: ")
                .append(String.join(", ", r.rulesEvaluated())).append(".").append(NL).append(NL);
        if (!r.violations().isEmpty()) {
            sb.append("| Rule | Severity | Violation | Location |").append(NL).append("|---|---|---|---|").append(NL);
            for (PolicyReport.Violation v : r.violations()) {
                sb.append("| ").append(v.ruleId()).append(" | ").append(v.severity()).append(" | ").append(cell(v.message()))
                        .append(" | ").append(cell(v.location())).append(" |").append(NL);
            }
            sb.append(NL);
        }
        return sb.toString();
    }

    private String documentation(DocumentationBundle d) {
        StringBuilder sb = new StringBuilder("#### Release notes: ").append(cell(d.title())).append(NL).append(NL)
                .append("> ").append(cell(d.executionDisclosure())).append(NL).append(NL)
                .append(cell(d.summary())).append(NL).append(NL)
                .append("#### Traceability").append(NL).append(NL)
                .append("| Criterion | Requirement | Tasks | Components |").append(NL).append("|---|---|---|---|").append(NL);
        for (DocumentationBundle.TraceRow row : d.traceability()) {
            sb.append("| ").append(row.criterionId()).append(" | ").append(row.requirementId()).append(": ").append(cell(row.requirement()))
                    .append(" | ").append(join(row.tasks())).append(" | ").append(join(row.components())).append(" |").append(NL);
        }
        sb.append(NL).append("#### Components changed").append(NL).append(NL);
        d.components().forEach(c -> sb.append("- `").append(c.component()).append("` (").append(c.change()).append("): ")
                .append(cell(c.reason())).append(NL));
        sb.append(NL).append("#### Assumptions to confirm").append(NL).append(NL);
        list(sb, d.assumptions());
        sb.append("#### Out of scope").append(NL).append(NL);
        list(sb, d.outOfScope());
        return sb.toString();
    }

    private String readiness(ReadinessReport r) {
        StringBuilder sb = new StringBuilder(r.ready() ? "**READY** for approval" : "**NOT READY**")
                .append(". ").append(cell(r.recommendation())).append(NL).append(NL)
                .append("Approval subject: ").append(String.join(", ", r.approvalSubject())).append(NL).append(NL)
                .append("| Check | Blocking | Result | Detail |").append(NL).append("|---|---|---|---|").append(NL);
        for (ReadinessReport.Check c : r.checks()) {
            sb.append("| ").append(c.id()).append(": ").append(cell(c.description())).append(" | ").append(c.blocking() ? "yes" : "no")
                    .append(" | ").append(c.passed() ? "pass" : "FAIL").append(" | ").append(cell(c.detail())).append(" |").append(NL);
        }
        sb.append(NL);
        if (!r.openAssumptions().isEmpty()) {
            sb.append("Open assumptions:").append(NL).append(NL);
            list(sb, r.openAssumptions());
        }
        return sb.toString();
    }

    private void list(StringBuilder sb, List<String> items) {
        if (items.isEmpty()) {
            sb.append("_None._").append(NL).append(NL);
            return;
        }
        items.forEach(i -> sb.append("- ").append(cell(i)).append(NL));
        sb.append(NL);
    }

    private String join(List<String> items) {
        return items.isEmpty() ? "-" : cell(String.join(", ", items));
    }

    private String cell(String s) {
        return agentRenderer.cell(s);
    }
}
