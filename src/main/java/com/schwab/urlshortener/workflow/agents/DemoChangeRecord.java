package com.schwab.urlshortener.workflow.agents;

import com.schwab.urlshortener.agentic.model.ImpactAnalysis;
import com.schwab.urlshortener.agentic.model.ImplementationPlan;
import com.schwab.urlshortener.agentic.model.RequirementSpec;
import com.schwab.urlshortener.workflow.workspace.PatchProposal;

import java.util.List;
import java.util.Locale;

/**
 * The DETERMINISTIC_DEMO patch: a change-record document written to
 * {@code docs/changes/run-{id}-{slug}.md}. It's a real file in a real git diff,
 * so the whole patch pipeline (change control, worktree, validation commands,
 * review, promotion, compensation) runs end to end without a model. It is NOT
 * product code, and its first line says so. Producing code changes requires LLM
 * mode.
 */
final class DemoChangeRecord {

    private DemoChangeRecord() {
    }

    static PatchProposal author(Long runId, String title, RequirementSpec spec, ImpactAnalysis design, ImplementationPlan plan) {
        String slug = title.toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9]+", "-").replaceAll("(^-|-$)", "");
        if (slug.isEmpty()) {
            slug = "change";
        }
        if (slug.length() > 50) {
            slug = slug.substring(0, 50);
        }
        String path = "docs/changes/run-" + runId + "-" + slug + ".md";
        StringBuilder md = new StringBuilder()
                .append("> Generated by the workflow orchestrator in DETERMINISTIC_DEMO mode. This is a change record, not product code.\n\n")
                .append("# Change record: ").append(title).append("\n\n")
                .append(spec.summary()).append("\n\n## Requirements\n\n");
        Checks.safe(spec.functionalRequirements()).forEach(s -> md.append("- **").append(s.id()).append("** ").append(s.text()).append('\n'));
        Checks.safe(spec.nonFunctionalRequirements()).forEach(s -> md.append("- **").append(s.id()).append("** ").append(s.text()).append('\n'));
        md.append("\n## Acceptance criteria\n\n");
        Checks.safe(spec.acceptanceCriteria()).forEach(ac -> md.append("- **").append(ac.id()).append("** (").append(ac.sourceRequirementId())
                .append(") then ").append(ac.then()).append('\n'));
        md.append("\n## Components\n\n");
        Checks.safe(design.impactedComponents()).forEach(c -> md.append("- `").append(c.component()).append("`: ").append(c.changeType()).append('\n'));
        Checks.safe(design.newComponents()).forEach(c -> md.append("- `").append(c.name()).append("` (new, ").append(c.packageName()).append(")\n"));
        md.append("\n## Planned tasks\n\n| Task | Depends on | Criteria |\n|---|---|---|\n");
        Checks.safe(plan.tasks()).forEach(t -> md.append("| ").append(t.id()).append(" ").append(t.title().replace("|", "/")).append(" | ")
                .append(String.join(", ", Checks.safe(t.dependsOn()))).append(" | ")
                .append(String.join(", ", Checks.safe(t.acceptanceCriteria()))).append(" |\n"));
        md.append("\n## Assumptions to confirm\n\n");
        List<RequirementSpec.Ambiguity> ambiguities = Checks.safe(spec.ambiguities());
        if (ambiguities.isEmpty()) {
            md.append("_None._\n");
        } else {
            ambiguities.forEach(a -> md.append("- **").append(a.id()).append("** ").append(a.assumption()).append('\n'));
        }
        return new PatchProposal("Add change record for '" + title + "' (demo patch).",
                List.of(new PatchProposal.FileChange(path, md.toString(),
                        "Records the planned change, its criteria, and its tasks for review (DETERMINISTIC_DEMO).")));
    }
}
