package com.schwab.urlshortener.agentic.review;

import com.schwab.urlshortener.agentic.AgenticFixtures;
import com.schwab.urlshortener.agentic.agent.AgentContext;
import com.schwab.urlshortener.agentic.model.ArtifactSource;
import com.schwab.urlshortener.agentic.model.ExecutionMode;
import com.schwab.urlshortener.agentic.model.ImpactAnalysis;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class MarkdownRendererTest {

    private final MarkdownRenderer renderer = new MarkdownRenderer();
    private final AgentContext ctx = AgenticFixtures.runDeterministicPipeline(AgenticFixtures.TITLE, AgenticFixtures.REQUIREMENT);

    @Test
    void banner_saysPlainlyWhetherAModelWasCalled() {
        assertThat(renderer.banner(ExecutionMode.DETERMINISTIC_DEMO, null))
                .contains("DETERMINISTIC_DEMO").contains("No language model was called").contains("not as AI analysis");
        assertThat(renderer.banner(ExecutionMode.LLM, "claude-opus-5"))
                .contains("LLM (`claude-opus-5`)").contains("review before acting");
    }

    @Test
    void provenance_distinguishesAllThreeSources() {
        assertThat(renderer.provenance(ArtifactSource.LLM, "m")).contains("generated by `m`");
        assertThat(renderer.provenance(ArtifactSource.DETERMINISTIC_DEMO, null)).contains("No model was called");
        assertThat(renderer.provenance(ArtifactSource.DETERMINISTIC_GUARDRAIL, null)).contains("never model-generated");
    }

    @Test
    void everyArtifactType_rendersItsSection() {
        assertThat(renderer.render(ctx.requirementSpec())).startsWith("## 1. Requirements").contains("| AC-1 | FR-1 |").contains("AMB-1");
        assertThat(renderer.render(ctx.impactAnalysis())).startsWith("## 2. Impact analysis").contains("`UrlMapping`");
        assertThat(renderer.render(ctx.implementationPlan())).startsWith("## 3. Implementation plan").contains("| T-1 |");
        assertThat(renderer.render(ctx.testPlan())).startsWith("## 4. Test plan").contains("| TC-1 |");
        assertThat(renderer.render(ctx.riskAssessment())).startsWith("## 5. Risk assessment").contains("| R-1 |");
        assertThat(renderer.render(new QualityGateReviewer().review(ctx))).startsWith("## 6. Quality gate").contains("**PASSED**");
    }

    @Test
    void emptySections_renderPlaceholders_andProposedComponentsAppear() {
        String md = renderer.render(new ImpactAnalysis(List.of(),
                List.of(new ImpactAnalysis.ProposedComponent("XService", "com.x", "does x")), null, null));

        assertThat(md).contains("_No existing component matched._").contains("`XService` in `com.x`").contains("_None._");
        assertThat(md).doesNotContain("### Data flows");
    }

    @Test
    void dataFlows_renderAsArrowPaths() {
        String md = renderer.render(new ImpactAnalysis(List.of(), List.of(), List.of(),
                List.of(new ImpactAnalysis.DataFlow("Redirect path", List.of("RedirectController", "UrlMappingRepository"), "clicks"))));

        assertThat(md).contains("### Data flows").contains("**Redirect path**: `RedirectController` → `UrlMappingRepository`. clicks");
    }

    @Test
    void tableCells_escapePipesAndFlattenNewlines() {
        assertThat(renderer.cell("a|b\nc")).isEqualTo("a\\|b c");
        assertThat(renderer.cell(null)).isEmpty();
    }

    @Test
    void unknownArtifactType_isRejected() {
        assertThatThrownBy(() -> renderer.render("not an artifact")).isInstanceOf(IllegalArgumentException.class);
    }
}
